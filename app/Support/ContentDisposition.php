<?php

declare(strict_types=1);

namespace UniTest\Support;

/**
 * RFC 5987 Content-Disposition для кириллицы в имени файла.
 */
final class ContentDisposition
{
    public static function attachment(string $filename): string
    {
        $filename = str_replace(["\r", "\n", '"'], '', $filename);
        $ascii = self::asciiFallback($filename);
        $encoded = rawurlencode($filename);

        return 'attachment; filename="' . $ascii . '"; filename*=UTF-8\'\'' . $encoded;
    }

    private static function asciiFallback(string $filename): string
    {
        $map = [
            'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'е' => 'e', 'ё' => 'e',
            'ж' => 'zh', 'з' => 'z', 'и' => 'i', 'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm',
            'н' => 'n', 'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't', 'у' => 'u',
            'ф' => 'f', 'х' => 'h', 'ц' => 'c', 'ч' => 'ch', 'ш' => 'sh', 'щ' => 'sch', 'ъ' => '',
            'ы' => 'y', 'ь' => '', 'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
            'А' => 'A', 'Б' => 'B', 'В' => 'V', 'Г' => 'G', 'Д' => 'D', 'Е' => 'E', 'Ё' => 'E',
            'Ж' => 'Zh', 'З' => 'Z', 'И' => 'I', 'Й' => 'Y', 'К' => 'K', 'Л' => 'L', 'М' => 'M',
            'Н' => 'N', 'О' => 'O', 'П' => 'P', 'Р' => 'R', 'С' => 'S', 'Т' => 'T', 'У' => 'U',
            'Ф' => 'F', 'Х' => 'H', 'Ц' => 'C', 'Ч' => 'Ch', 'Ш' => 'Sh', 'Щ' => 'Sch', 'Ъ' => '',
            'Ы' => 'Y', 'Ь' => '', 'Э' => 'E', 'Ю' => 'Yu', 'Я' => 'Ya',
        ];
        $translit = strtr($filename, $map);
        $ascii = preg_replace('/[^A-Za-z0-9._-]+/', '_', $translit) ?: 'download';
        $ascii = trim($ascii, '._-') ?: 'download';

        return $ascii;
    }
}
